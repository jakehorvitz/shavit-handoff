def datauri(p: pathlib.Path) -> str:
    if not p.exists():
        print(f"WARN missing {p}", file=sys.stderr)
        return ""
    mime = "image/jpeg" if p.suffix.lower() in (".jpg", ".jpeg") else "image/png"
    return f"data:{mime};base64," + base64.b64encode(p.read_bytes()).decode()

