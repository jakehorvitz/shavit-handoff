# tile spec: ('new', key, badge, pin, ba) | ('old', label) | ('pinold', label)
def mini_tile(spec):
    kind = spec[0]
    if kind in ("old", "pinold"):
        label = spec[1]
        tag = '<span class="mpin">📌</span>' if kind == "pinold" else ''
        return f'<span class="mtile mold">{tag}<span class="moldlab">{label}</span></span>'
    _, key, badge, pin, ba = spec
    pins = '<span class="mpin">📌</span>' if pin else ''
    b = f'<span class="mbadge">{badge}</span>' if badge else ''
    baw = '<span class="mba"></span>' if ba else ''
    return f'<span class="mtile bg-{key}">{pins}{b}{baw}</span>'

